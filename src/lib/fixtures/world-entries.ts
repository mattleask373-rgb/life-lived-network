/**
 * DEMONSTRATION records — not real activity, and never presented as real.
 *
 * The live world has no user population yet, so a small, deliberately thin
 * trial layer exists for the first three localities: Birmingham (urban),
 * Bristol (city and creative) and Herefordshire (rural and dispersed). It is
 * here to show the same system working in different kinds of place.
 *
 * Rules these records obey, without exception:
 *   - every one carries `demonstration: true`, and the interface says so
 *   - no real person, business, venue or event is named or impersonated
 *   - no photographs, no reviews, no testimonials, no invented history
 *   - each belongs to one real locality, so a quiet place stays quiet
 *
 * Deleting this file removes the entire trial layer without touching anything
 * architectural.
 */

import type { WorldEntry } from "../world-data";

export interface DemoEntry extends WorldEntry {
  /** The real locality this demonstration record belongs to. */
  placeSlug: string;
}

function demo(
  entry: Omit<DemoEntry, "demonstration" | "community" | "verified" | "host">,
): DemoEntry {
  return {
    ...entry,
    demonstration: true,
    community: false,
    verified: false,
    host: "Demonstration record — not a real listing",
    quality: entry.quality ?? "unverified",
    currency: entry.currency ?? "GBP",
  };
}

/**
 * A real instant a given number of days ahead, so a demonstration with a date
 * is always genuinely upcoming rather than quietly stale.
 */
function soon(days: number, hour: number, minute: number): string {
  const at = new Date();
  at.setDate(at.getDate() + days);
  at.setHours(hour, minute, 0, 0);
  return at.toISOString();
}

